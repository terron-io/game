/**
 * Период расписания в минутах от начала часа. 60 = ровно в HH:00.
 * ⚠️ СЕЙЧАС 10 (:10 :20 :30…) — по решению владельца 28.07 крутим так и НА
 * ПРОДЕ, пока обкатываем механику (за час одна проверка — слишком долго).
 * Вернуть 60, когда наиграется.
 * Это ДЕФОЛТ: сервер может переопределить его из окружения (TERRON_GOLDEN_PERIOD_MIN,
 * см. ServerEnv.applyEventScheduleFromEnv) — тогда правка времени не требует пересборки.
 */
export const TERRON_GOLDEN_PERIOD_MINUTES = 10;
let goldenPeriodMinutes: number = TERRON_GOLDEN_PERIOD_MINUTES;

/** Действующий период золотого матча в минутах (дефолт + оверрайд окружения). */
export function goldenPeriodMin(): number {
  return goldenPeriodMinutes;
}

/** Переопределить период золотого. Зовёт ТОЛЬКО сервер на старте (из env). */
export function setGoldenPeriodMin(minutes: number): void {
  if (!Number.isInteger(minutes) || minutes < 1 || minutes > 1440) {
    throw new Error(`bad golden period: ${minutes}`);
  }
  goldenPeriodMinutes = minutes;
}
/**
 * За сколько до старта золотое лобби становится ГЛАВНЫМ на витрине: вкладки
 * меняются местами и золотая делается активной. ТОЛЬКО ВИТРИНА — на работу
 * обычной карусели это не влияет никак (см. «устройство» выше).
 */
export const TERRON_GOLDEN_FEATURE_LEAD_MS = 70 * 1000;
/** Награда победителю золотого матча, кровавых алмазов (ПТС). */
export const TERRON_GOLDEN_REWARD_PTS = 10;

/**
 * Ближайший золотой матч СТРОГО в будущем (мс эпохи) от `now`.
 * Слот, попавший в «тихое окно» вокруг АЛМАЗНОГО матча, пропускается — иначе
 * в 20:00 стартовали бы оба события сразу и растащили онлайн пополам
 * (см. TERRON_DIAMOND_QUIET_MS ниже).
 */
export function nextGoldenMatchAt(now: number): number {
  const period = goldenPeriodMin() * 60_000;
  let at = Math.floor(now / period) * period + period;
  // Кап на всякий случай: тихое окно всегда меньше суток, столько шагов хватит
  // с запасом даже при периоде 60 минут.
  for (let i = 0; i < 48 && isNearDiamondMatch(at); i++) at += period;
  return at;
}


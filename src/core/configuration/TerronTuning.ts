export function getDiamondSchedule(): DiamondSchedule {
  return diamondSchedule;
}

/** Раз в сутки в ЧЧ:ММ по Москве. */
export function setDiamondDaily(hour: number, minute: number): void {
  if (!Number.isInteger(hour) || hour < 0 || hour > 23) {
    throw new Error(`bad diamond hour: ${hour}`);
  }
  if (!Number.isInteger(minute) || minute < 0 || minute > 59) {
    throw new Error(`bad diamond minute: ${minute}`);
  }
  diamondSchedule = { kind: "daily", hour, minute };
}

/** Каждые N минут от начала часа (для обкатки — «раз в полчаса»). */
export function setDiamondEvery(minutes: number): void {
  if (!Number.isInteger(minutes) || minutes < 5 || minutes > 720) {
    throw new Error(`bad diamond period: ${minutes}`);
  }
  diamondSchedule = { kind: "every", minutes };
}

export function diamondRewardPts(): number {
  return diamondReward;
}

export function setDiamondRewardPts(pts: number): void {
  if (!Number.isInteger(pts) || pts < 1 || pts > 500) {
    throw new Error(`bad diamond reward: ${pts}`);
  }
  diamondReward = pts;
}

/** «20:00 МСК» / «каждые 30 мин» — для логов и подписей. */
export function diamondScheduleLabel(): string {
  const s = diamondSchedule;
  return s.kind === "every"
    ? `каждые ${s.minutes} мин`
    : `${String(s.hour).padStart(2, "0")}:${String(s.minute).padStart(2, "0")} МСК`;
}

/**
 * За сколько до старта алмазная вкладка витрины встаёт первой и активной.
 * Больше золотого лида (70с): событие суточное, у людей должно быть время
 * увидеть и зайти.
 */
export const TERRON_DIAMOND_FEATURE_LEAD_MS = 10 * 60 * 1000;

/** Насколько вокруг алмазного слота глушится золотой (в обе стороны). */
export const TERRON_DIAMOND_QUIET_MS = 5 * 60 * 1000;

const MSK_OFFSET_MS = 3 * 60 * 60 * 1000;
const DAY_MS = 24 * 60 * 60 * 1000;

/** Алмазный слот ТЕХ СУТОК (по МСК), в которые попадает `ts` (суточный режим). */
function diamondSlotOfDay(
  ts: number,
  s: { hour: number; minute: number },
): number {
  const mskMidnight = Math.floor((ts + MSK_OFFSET_MS) / DAY_MS) * DAY_MS;
  return mskMidnight + (s.hour * 60 + s.minute) * 60_000 - MSK_OFFSET_MS;
}

/** Ближайший алмазный матч СТРОГО в будущем (мс эпохи) от `now`. */
export function nextDiamondMatchAt(now: number): number {
  const s = diamondSchedule;
  if (s.kind === "every") {
    const period = s.minutes * 60_000;
    return Math.floor(now / period) * period + period;
  }
  const at = diamondSlotOfDay(now, s);
  return at > now ? at : at + DAY_MS;
}

/** Попадает ли момент в тихое окно вокруг алмазного матча. */
export function isNearDiamondMatch(ts: number): boolean {
  if (!TERRON_DIAMOND_ENABLED) return false;
  const s = diamondSchedule;
  if (s.kind === "every") {
    const period = s.minutes * 60_000;
    const nearest = Math.round(ts / period) * period;
    return Math.abs(ts - nearest) <= TERRON_DIAMOND_QUIET_MS;
  }
  const today = diamondSlotOfDay(ts, s);
  return [today - DAY_MS, today, today + DAY_MS].some(
    (slot) => Math.abs(ts - slot) <= TERRON_DIAMOND_QUIET_MS,
  );
}

/** Награда победителю событийного матча по тиру лобби. */
export function eventRewardPts(tier: string | undefined): number {
  return tier === "diamond" ? diamondRewardPts() : TERRON_GOLDEN_REWARD_PTS;
}

/**
 * Награда, которую показываем игроку. Берём ИЗ КОНФИГА ЛОББИ (его прислал сервер),
 * а к константе падаем только для старых снимков без поля: цифру крутят
 * переменной окружения, и клиентский бандл про её текущее значение не знает.
 */
export function eventRewardOf(
  config: { eventTier?: string; eventRewardPts?: number } | null | undefined,
): number {
  return config?.eventRewardPts ?? eventRewardPts(config?.eventTier);
}


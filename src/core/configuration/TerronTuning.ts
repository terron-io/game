/** Золото за каст «Перенос» (настоящая цена — войска, до 30%). */
// ⚠️ 25.08 (решение владельца «сделай перенос бесплатным, чтобы по одному
// зданию переносить»): каст БЕСПЛАТНЫЙ. Цена ульты — единственный на матч
// выбор ульты и её замок, а не золото за каждый переезд.
export const TERRON_WALK_COST = 0;
/**
 * ⚠️ 25.08: зоны переноса БОЛЬШЕ НЕТ (переносим одно здание), войска каст не
 * тратит. Константы ниже оставлены только чтобы не ломать чужие импорты —
 * новый код их не использует.
 */
export const TERRON_WALK_RATIO_MAX = 0.3;
/** Прощение промаха по зданию: клик редко попадает в тайл пиксель-в-пиксель. */
export const TERRON_WALK_PICK_RADIUS = 4;
/**
 * Радиус зоны при доле 0 (минимальный «пятачок»).
 * 25.08 (решение владельца «базовый радиус в 3 раза меньше»): 8 → 3 — на нуле
 * слайдера зона захватывала соседние здания, которые двигать не собирались.
 */
export const TERRON_WALK_RADIUS_BASE = 3;
/** Прибавка радиуса на единицу доли (0.3 → +30 тайлов). */
export const TERRON_WALK_RADIUS_PER_RATIO = 100;
/**
 * Радиус зоны переноса от доли войск. ОДИН расчёт на сим и клиент
 * (гост рисует ровно тот круг, по которому сим соберёт здания).
 * Ориентиры владельца: 5% ≈ 1 здание, 10% ≈ 2, 30% ≈ городок из 4-6.
 */
export function walkZoneRadius(ratio: number): number {
  const r = Math.max(0, Math.min(TERRON_WALK_RATIO_MAX, ratio));
  return Math.round(TERRON_WALK_RADIUS_BASE + r * TERRON_WALK_RADIUS_PER_RATIO);
}

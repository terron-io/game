/**
 * terron 23.08 — КАК ВЫГЛЯДИТ ГОСТ ЭТОГО ЮНИТА. Одна функция на всю игру.
 *
 * ⚠️ Требование владельца после вечера с двумя гостами на одной кнопке:
 * «что есть сущность, и у неё должны быть все параметры». Гост рисуют ЧЕТЫРЕ
 * независимых прохода рендера (звезда строения, круг радиуса, флаг, крестик),
 * и до этого каждый решал сам, ручным списком типов: `CrosshairPass` знал два
 * типа, `Renderer` — те же два ещё раз (ленивое создание прохода), а канвас —
 * третьим списком. Результат: на одной кнопке два госта, у другого каста — ни
 * одного.
 *
 * Теперь вопрос «какой у этого юнита гост» имеет РОВНО ОДИН ответ — здесь.
 * Новый юнит/каст ничего не рисует «по месту»: он либо попадает под общее
 * правило, либо получает строку в списке исключений ниже.
 */
import { Structures, ULTIMATE_REGISTRY, UnitType } from "../core/game/Game";

export type GhostKind =
  /** Звезда с иконкой (все строения и ульт-штабы) — рисует StructurePass. */
  | "star"
  /** Иконка юнита под курсором — рисует WarshipPreviewController. */
  | "icon"
  /** Круг радиуса вокруг цели/юнита — RangeCirclePass. */
  | "circle"
  /** Своё превью (флаг Раскола, флаг Блокады) — канвас-оверлей. */
  | "own"
  /** Ничего своего нет → прицел-крестик, CrosshairPass. */
  | "crosshair";

/**
 * Юниты, у которых превью рисует канвас-оверлей (SplitPreviewController).
 * Крестик им не нужен — иначе получится два госта об одном и том же.
 */
const OWN_PREVIEW: readonly UnitType[] = [UnitType.Split, UnitType.Blockade];

/**
 * Юниты, у которых гост — ИКОНКА ПОД КУРСОРОМ (её рисует
 * WarshipPreviewController, беря картинку из реестра подмен).
 *
 * ⚠️ ПРАВИЛО ВЛАДЕЛЬЦА 23.08: «крестики — это гост, конкретный класс. ОДИН
 * гост на один юнит, если не сказано иное». Поэтому тип, попавший сюда, НЕ
 * получает крестик: у него уже есть свой гост.
 */
const ICON_GHOST: readonly UnitType[] = [UnitType.Warship];

/**
 * @param rangeRadius радиус круга, который уже посчитал контроллер (0 = круга
 *        нет). Он зависит от уровня здания и множителей ульты, поэтому
 *        приходит снаружи, а не хранится тут.
 */
export function ghostKindFor(type: UnitType, rangeRadius: number): GhostKind {
  if (Structures.has(type)) return "star";
  if (ICON_GHOST.includes(type)) return "icon";
  if (OWN_PREVIEW.includes(type)) return "own";
  if (rangeRadius > 0) return "circle";
  // Каст, объявивший зону в реестре, но пока не получивший радиус (например,
  // орудия ещё нет) — всё равно НЕ крестик: у него своя зона по смыслу.
  const cast = ULTIMATE_REGISTRY.find((u) => u.cast?.type === type)?.cast;
  if (cast !== undefined && cast.previewRadius > 0) return "circle";
  return "crosshair";
}

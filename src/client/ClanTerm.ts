import { getCurrentLang } from "./Utils";

// Мультиязычное имя/описание клана. EN — БАЗА и фолбэк (всегда заполнена). RU —
// опциональный оверлей: показываем его ТОЛЬКО на ru-локали и если он непустой,
// иначе всегда падаем на английскую базу. См. multilang.md.
export function localizeClanText(baseEn: string, ru?: string | null): string {
  const t = (ru ?? "").trim();
  return getCurrentLang() === "ru" && t ? t : baseEn;
}

// Варианты «скобок» вокруг тега. Уникальна сама строка ТЕГА; скобки — косметика
// отображения. Индекс в этом массиве хранится в clans.bracket. ОБЩИЙ источник для
// формы создания и страницы клана (порядок менять нельзя — это и есть индекс).
export const BRACKETS = [
  { id: "square", l: "[", r: "]" },
  { id: "angle", l: "‹", r: "›" },
  { id: "brace", l: "{", r: "}" },
  { id: "paren", l: "(", r: ")" },
  { id: "guillemet", l: "«", r: "»" },
  { id: "none", l: "", r: "" },
] as const;

export function bracketPair(i: number): { l: string; r: string } {
  return BRACKETS[i] ?? BRACKETS[0];
}


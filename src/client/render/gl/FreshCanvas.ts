/**
 * terron 13.09 — НОВЫЙ ХОЛСТ ВМЕСТО ОЖИДАНИЯ БРАУЗЕРА.
 *
 * После потери WebGL-контекста мы ждали событие `webglcontextrestored`, а оно
 * почти никогда не приходит вовремя: прод за неделю до 12.09 — 915 потерь,
 * вернулось за 10 с только 141, окно «перезагрузить» получили 276. Тест
 * владельца 13.09 (Mac M5, Яндекс.Браузер, `browser://gpucrash`): браузер
 * держал графику ~30 с, всё это время карта была белой.
 *
 * Потерянный контекст к холсту привязан намертво — `getContext` отдаёт тот же
 * мёртвый объект. Новый холст получает НОВЫЙ контекст сразу, как только
 * GPU-процесс снова жив. Поэтому после первой потери (см. ContextLossPolicy)
 * не дожидаемся браузер дольше FRESH_CANVAS_AFTER_MS, а пересобираем рендер
 * на свежем холсте — без перезагрузки страницы и без выхода из матча.
 */
export const FRESH_CANVAS_AFTER_MS = 2500;

/**
 * Поставить свежий холст на место потерявшего контекст.
 *
 * ⚠️ Старый холст НЕ удаляем: контроллеры оверлеев (SplitPreview, MineField,
 * MirvPreview, WarshipPreview, BunkerFire, TankFront) держат ссылку на него и
 * снимают себя, как только он пропадёт из документа (`!isConnected` = «матч
 * кончился»). Удаляет его раннер вместе с концом матча, как и раньше.
 * ⚠️ Прячем через visibility, а не display: раннер меряет камеру по размеру
 * СТАРОГО холста (ResizeObserver в mountWebGLFrameLoop), при display:none
 * размер стал бы нулём.
 * id уезжает на новый холст — по нему его находят HideUiMode и контроллеры,
 * которые стартуют позже. Новый встаёт ПЕРЕД старым: оверлеи вставлены после
 * старого и остаются поверх карты.
 */
export function swapInFreshCanvas(old: HTMLCanvasElement): HTMLCanvasElement {
  const fresh = old.cloneNode(false) as HTMLCanvasElement;
  if (old.id) old.id = `${old.id}-lost`;
  old.style.visibility = "hidden";
  old.before(fresh);
  return fresh;
}

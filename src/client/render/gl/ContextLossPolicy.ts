/**
 * terron 05.09 — ЧТО ДЕЛАТЬ ПОСЛЕ ПОТЕРИ WEBGL-КОНТЕКСТА.
 *
 * Хелс за неделю: «WebGL2 not supported: Web page caused context loss and was
 * blocked» — 223 сессии. Это Chrome ЗАБЛОКИРОВАЛ WebGL для сайта на весь сеанс
 * браузера, потому что наша страница «виновна» в нескольких сбросах GPU подряд.
 * У 26 из них в той же сессии было 2–4 потери за 10–60 с: после `restored` мы
 * немедленно пересобирали ПОЛНЫЙ рендер на той же нагрузке — GPU падал снова,
 * и вторая-третья «виновная» потеря включала блок. Остальные 196 — страницы,
 * загруженные УЖЕ под блоком (он держится до перезапуска браузера).
 *
 * Политика (чистая функция — под тестом):
 *  - потеря №1 → восстанавливаемся, но В ЩАДЯЩЕМ РЕЖИМЕ (потолок кадров, без
 *    ленивых тяжёлых пассов) — второго сброса надо избежать любой ценой;
 *  - потеря №2 и дальше → GL больше НЕ ТРОГАЕМ: не пересобираем, сразу
 *    предлагаем перезагрузку. Третий сброс — это блок WebGL до перезапуска
 *    браузера, а перезагрузка страницы = свежий старт уже в щадящем режиме
 *    (флаг terron_gfx_low переживает перезагрузку).
 */
export type ContextLossDecision = "rebuild-safe" | "give-up";

export function contextLossDecision(lossNo: number): ContextLossDecision {
  return lossNo >= 2 ? "give-up" : "rebuild-safe";
}

/** Chrome-текст блокировки — по нему модалка говорит про перезапуск браузера. */
export const WEBGL_BLOCKED_RE = /caused context loss and was blocked/i;

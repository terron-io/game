// Домен (без www) → slug иконки. Порядок не важен: берём по суффиксу хоста.
const HOST_TO_SLUG: Array<[string[], string]> = [
  [["youtube.com", "youtu.be"], "youtube"],
  [["vk.com", "vk.ru", "vkontakte.ru"], "vk"],
  [["t.me", "telegram.me", "telegram.org"], "telegram"],
  [["tiktok.com"], "tiktok"],
  [["instagram.com", "instagr.am"], "instagram"],
  [["twitch.tv"], "twitch"],
  [["ok.ru", "odnoklassniki.ru"], "odnoklassniki"],
  [["x.com", "twitter.com"], "x"],
  [["discord.gg", "discord.com", "discordapp.com"], "discord"],
  [["boosty.to"], "boosty"],
];

function slugForHost(host: string): string | null {
  const h = host.toLowerCase().replace(/^www\./, "");
  for (const [domains, slug] of HOST_TO_SLUG) {
    for (const d of domains) {
      if (h === d || h.endsWith("." + d)) return slug;
    }
  }
  return null;
}


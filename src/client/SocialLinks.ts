// Путь ссылки без домена: pathname+search+hash, декодированный, без хвостового «/».
function displayPath(u: URL): string {
  let p = (u.pathname + u.search + u.hash).replace(/\/+$/, "");
  try {
    p = decodeURI(p);
  } catch {
    /* оставляем как есть */
  }
  return p || "/";
}

// Разбивает свободный текст на строки и кликабельные соц-ссылки (только вайтлист).
// Возвращает массив для прямой вставки в Lit-шаблон: ${linkifySocials(text)}.
export function linkifySocials(text: string): Array<string | TemplateResult> {
  if (!text) return [];
  const out: Array<string | TemplateResult> = [];
  const re = /(https?:\/\/[^\s<]+)/gi;
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) out.push(text.slice(last, m.index));
    last = re.lastIndex;

    let raw = m[1];
    // Отрезаем «прилипшую» хвостовую пунктуацию (не часть адреса).
    let trailing = "";
    const tm = raw.match(/[)\].,;!?»"']+$/);
    if (tm) {
      trailing = tm[0];
      raw = raw.slice(0, -trailing.length);
    }

    let link: TemplateResult | null = null;
    try {
      const u = new URL(raw);
      const slug = slugForHost(u.hostname);
      if (slug) {
        link = html`<a
          class="t-social"
          href=${raw}
          target="_blank"
          rel="noopener noreferrer"
          title=${raw}
          @click=${(e: Event) => e.stopPropagation()}
          >${icon(slug)}<span class="t-social-path">${displayPath(u)}</span
          >${externalIcon}</a
        >`;
      }
    } catch {
      /* не URL — оставляем как текст */
    }

    out.push(link ?? raw);
    if (trailing) out.push(trailing);
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}
